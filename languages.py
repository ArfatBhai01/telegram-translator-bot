def resolve_lang(user_input: str):
    if not user_input: return None
    q = user_input.strip().lower()
    for code in LANGUAGES:
        if code.lower() == q: return code
    if q in ALIASES: return ALIASES[q]
    for code, (eng, native) in LANGUAGES.items():
        if q == eng.lower(): return code
    return None

